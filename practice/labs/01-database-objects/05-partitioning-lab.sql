-- This script demonstrates the creation, management, and optimization of partitioned tables and
-- indexes in SQL Server, covering:
--   1. Creating a Partition Function (RANGE RIGHT) and Partition Scheme
--   2. Creating partitioned tables and aligned indexes
--   3. Querying Partitions via DMV and the $PARTITION system function
